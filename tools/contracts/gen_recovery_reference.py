"""Generate the reference Recovery Package v1 (E-03, MVP 12 "a reference Recovery Package").

    uv run python tools/contracts/gen_recovery_reference.py          # rewrite the files
    uv run python tools/contracts/gen_recovery_reference.py --check  # CI: files are current

Every input is fixed (recovery key, keys, salt, nonce, ids, time), so the bytes are stable. The
keys here are test values that protect nothing. services/backend/tests/test_recovery_reference.py
unwraps the reference with its recovery key on every change, so every later build can still
restore a version-1 package; it also checks that changing any header field breaks the unwrap
(the authenticated header plays the role of MVP 9.4's ``auth_tag``).
"""

import json
import sys
import tempfile
from pathlib import Path

from aios_backend.apps.setup import recovery_package as rp

OUT = (
    Path(__file__).resolve().parents[2] / "contracts" / "recovery-package" / "v1" / "golden-vectors"
)

RECOVERY_KEY = bytes(range(10, 30))  # 20 bytes
DB_KEY = bytes(range(100, 132))
SIGNING_SEED = bytes(range(1, 33))
STREAM = "3f2a9c1e-7b4d-4e8f-9a01-0c1d2e3f4a5b"
FIXED = {
    "package_id": "9a9a9a9a-0000-4000-8000-000000000001",
    "created_at": "2026-11-12T09:00:00.000Z",
    "salt": bytes(range(200, 216)),
    "nonce": bytes(range(220, 232)),
}

README = """# Reference package: recovery-package v1

Generated by `tools/contracts/gen_recovery_reference.py` (E-03); CI fails if it drifts (`--check`).
`services/backend/tests/test_recovery_reference.py` unwraps `reference.pkg` with the recovery key
in `expected.json` on every change. The keys are test values and protect nothing.
"""


def generate(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    data, package_id = rp.write(
        recovery_key=RECOVERY_KEY,
        db_key=DB_KEY,
        signing_seed=SIGNING_SEED,
        stream_id=STREAM,
        security_state_revision={"migration": "0007", "catalogue": "2026-11-10"},
        evidence_tip={
            "stream_id": STREAM,
            "epoch": 1,
            "seq": 2,
            "event_hash": "ab" * 32,
        },
        writer_file="evidence.db",
        fixed=FIXED,
    )
    (out / "reference.pkg").write_bytes(data)
    expected = {
        "recovery_key": rp.format_recovery_key(RECOVERY_KEY),
        "package_id": package_id,
        "stream_id": STREAM,
        "db_key_hex": DB_KEY.hex(),
        "signing_seed_hex": SIGNING_SEED.hex(),
        "signing_key_id": rp.key_id(rp.public_key(SIGNING_SEED)),
        "required_files": ["chats.db", "evidence.db"],
        "evidence_tip_seq": 2,
    }
    (out / "expected.json").write_bytes(json.dumps(expected, indent=2).encode() + b"\n")
    (out / "README.md").write_text(README, encoding="utf-8", newline="\n")


def _snapshot(folder: Path) -> dict[str, bytes]:
    return {p.name: p.read_bytes() for p in sorted(folder.iterdir()) if p.is_file()}


def main(argv: list[str]) -> int:
    if "--check" in argv:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "v"
            generate(fresh)
            if _snapshot(fresh) != _snapshot(OUT):
                sys.stderr.write(
                    "the reference Recovery Package is out of date: run "
                    "`uv run python tools/contracts/gen_recovery_reference.py`\n"
                )
                return 1
        return 0
    generate(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
