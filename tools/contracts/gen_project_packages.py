"""Generate the golden packages of Project Package v1 (J-02, AC-16).

    uv run python tools/contracts/gen_project_packages.py          # rewrite the files
    uv run python tools/contracts/gen_project_packages.py --check  # CI: files are current

Fixed ids and times, so the bytes are stable. Every later build must import all three
(services/backend/tests/test_golden_packages.py):

* ``current.aiosproj``: what this version exports (all files and optional fields).
* ``older.aiosproj``: the oldest shape v1 allows (question 5: only version 1 exists, so "older"
  is a minimal v1 package): no optional manifest fields, no models.json, no summaries, no
  ``classification_source`` (readers default it).
* ``unknown-file.aiosproj``: a current package with a file type this version does not know; it is
  skipped with a warning and everything else imports.

Once v1 is FROZEN, a change to an existing package needs a new contract version and an ADR.
"""

