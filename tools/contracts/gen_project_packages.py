def generate(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    current = _current()
    (out / "current.aiosproj").write_bytes(current)
    (out / "older.aiosproj").write_bytes(_older())
    (out / "unknown-file.aiosproj").write_bytes(_with_unknown_file(current))
    (out / "expected.json").write_bytes(json.dumps(EXPECTED, indent=2).encode() + b"\n")
    (out / "README.md").write_text(README, encoding="utf-8", newline="\n")


def _snapshot(folder: Path) -> dict[str, bytes]:
    return {p.name: p.read_bytes() for p in sorted(folder.iterdir()) if p.is_file()}


def main(argv: list[str]) -> int:
    if "--check" in argv:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "v"
            generate(fresh)
            if _snapshot(fresh) != _snapshot(OUT):
                sys.stderr.write(
                    "project golden packages are out of date: run "
                    "`uv run python tools/contracts/gen_project_packages.py`\n"
                )
                return 1
        return 0
    if OUT.exists():
        for child in OUT.iterdir():
            if child.is_file():
                child.unlink()
            elif child.is_dir():
                shutil.rmtree(child)
    generate(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
