def _with_unknown_file(data: bytes) -> bytes:
    with zipfile.ZipFile(io.BytesIO(data)) as zf:
        files = {n: zf.read(n) for n in zf.namelist()}
    files["attachments/notes.md"] = b"# A file type a later version may add\n"
    return _zip(files)


