"""Generate the golden vectors of Evidence Wire Format v1 (F-02).

    uv run python tools/contracts/gen_evidence_vectors.py          # rewrite the files
    uv run python tools/contracts/gen_evidence_vectors.py --check  # CI: files are current

Inputs are fixed (seeds, clock, ids), so the output is byte-stable. The intact bundles come from
the real evidence writer (services/evidence-writer); the broken ones are made from them here by
hand, the way an attacker or a damaged copy would. The independent TypeScript verifier
(apps/verifier-cli) must reach the ``verdict`` in each folder's ``expected.json``.

Once v1 is FROZEN, a change to an existing vector needs a new contract version and an ADR; new
vectors may only be added.
"""

import io
import json
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path
from typing import Any

from aios_common.canonical import b64url, jcs, tagged_hash
from aios_evidence_writer import chain
from aios_evidence_writer import store as store_module
from aios_evidence_writer.keys import MemoryKeys
from aios_evidence_writer.store import EvidenceStore, Intent

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "contracts" / "evidence-wire-format" / "v1" / "golden-vectors"

STREAM = "3f2a9c1e-7b4d-4e8f-9a01-0c1d2e3f4a5b"
PROJECT_A = "a1a1a1a1-0000-4000-8000-000000000001"
PROJECT_B = "b2b2b2b2-0000-4000-8000-000000000002"
CONVERSATION = "c3c3c3c3-0000-4000-8000-000000000003"
MESSAGE = "d4d4d4d4-0000-4000-8000-000000000004"
SEED_1 = bytes(range(1, 33))  # key of epoch 1
SEED_2 = bytes(range(33, 65))  # key the restored device generates
SEED_FOREIGN = bytes(range(65, 97))  # nobody's key
NONCE_IN = bytes(range(100, 132))
NONCE_OUT = bytes(range(132, 164))
FIXED_ZIP_TIME = (1980, 1, 1, 0, 0, 0)

README = """# Golden vectors: evidence-wire-format v1

Generated by `tools/contracts/gen_evidence_vectors.py` (F-02); CI fails if they drift
(`--check`). Do not edit by hand.

Each folder holds one case: one or more export bundles (`*.zip`, section 10 of the spec) and
`expected.json` with the verdict the verifier must print (section 11) and, where useful, the
error code. Verify all bundles of a folder together.

| Case | Bundles | Verdict | What it shows |
| --- | --- | --- | --- |
| `intact` | `export.zip` | `intact` | A chain from genesis with checkpoints and a signed manifest |
| `project-scope` | `export.zip` | `intact` | A project export: the whole chain, with the project's first and last seq in `scope` |
| `restore-two-signers` | `export.zip` | `intact` | Restore: continuation to epoch 2, handover checkpoints by the old and the new key |
| `altered` | `export.zip` | `altered` | One event body changed after export (hash link breaks) |
| `truncated` | `export.zip` | `truncated` | The last events removed; the signed manifest kept |
| `branched` | `restored.zip`, `original.zip` | `branched` | The original device kept writing after the backup the restore used |
| `unknown-signer` | `export.zip` | `unknown_signer` | The manifest re-signed with a key the manifest does not name |

`commitments.json`: the input and output commitment example of section 8 (nonce, exact bytes,
expected digests). The writer and the verifier must both reproduce it.
"""


class Clock:
    """Each call is one second later, from a fixed start."""

    def __init__(self, start_minute: int = 0) -> None:
        self.n = start_minute * 60

    def __call__(self) -> str:
        self.n += 1
        minutes, seconds = divmod(self.n, 60)
        return f"2026-11-12T09:{minutes % 60:02d}:{seconds:02d}.000Z"


def _genesis(seed: bytes) -> Intent:
    public = chain.public_key(seed)
    return Intent(
        "genesis",
        "store_created",
        "2026-11-12T09:00:00.000Z",
        {"signing_key": b64url(public), "key_id": chain.key_id(public), "app_version": "0.1.0"},
    )


def _commitments() -> dict[str, Any]:
    input_bytes = jcs(
        {
            "model": "minicpm5-2b-q4_k_m-openbmb-gguf",
            "messages": [
                {"role": "system", "content": "You are a helpful assistant."},
                {"role": "user", "content": "What is the capital of Austria?"},
            ],
        }
    )
    output_bytes = b"Vienna is the capital of Austria."
    return {
        "input": {
            "tag": chain.TAG_INPUT,
            "nonce_b64url": b64url(NONCE_IN),
            "bytes_utf8": input_bytes.decode(),
            "commitment": chain.commitment(chain.TAG_INPUT, NONCE_IN, input_bytes),
        },
        "output": {
            "tag": chain.TAG_OUTPUT,
            "nonce_b64url": b64url(NONCE_OUT),
            "bytes_utf8": output_bytes.decode(),
            "commitment": chain.commitment(chain.TAG_OUTPUT, NONCE_OUT, output_bytes),
        },
        "rule": "commitment = SHA-256(UTF-8(tag) || 0x00 || nonce || bytes), lowercase hex",
    }


def _events(clock: Clock) -> list[Intent]:
    def at() -> str:
        return clock()

    def inference(n: int) -> Intent:
        return Intent(
            f"inference-{n}",
            "inference_completed",
            at(),
            {
                "conversation_id": CONVERSATION,
                "message_id": MESSAGE,
                "provider": "local",
                "model_id": "minicpm5-2b-q4_k_m-openbmb-gguf",
                "input_commitment": tagged_hash(chain.TAG_INPUT, bytes([n])),
                "output_commitment": tagged_hash(chain.TAG_OUTPUT, bytes([n])),
                "tokens_in": 40 + n,
                "tokens_out": 12 + n,
                "status": "ok",
            },
            PROJECT_A,
            CONVERSATION,
        )

    return [
        Intent(
            "project-a",
            "project_created",
            at(),
            {"project_id": PROJECT_A, "classification": "restricted"},
            PROJECT_A,
        ),
        Intent(
            "conversation",
            "conversation_created",
            at(),
            {
                "conversation_id": CONVERSATION,
                "project_id": PROJECT_A,
                "classification": "restricted",
            },
            PROJECT_A,
            CONVERSATION,
        ),
        inference(1),
        Intent(
            "project-b",
            "project_created",
            at(),
            {"project_id": PROJECT_B, "classification": "internal"},
            PROJECT_B,
        ),
        inference(2),
    ]


def _store(folder: Path, seed: bytes, clock: Clock) -> EvidenceStore:
    s = EvidenceStore(folder / "evidence.db", MemoryKeys(seed), clock=clock)
    s.init_stream(STREAM)
    return s


def _zip(files: dict[str, bytes]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in ("manifest.json", "manifest.sig.json", "events.jsonl", "checkpoints.jsonl"):
            entry = zipfile.ZipInfo(name, date_time=FIXED_ZIP_TIME)
            entry.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(entry, files[name])
    return buffer.getvalue()


def _unzip(data: bytes) -> dict[str, bytes]:
    with zipfile.ZipFile(io.BytesIO(data)) as zf:
        return {n: zf.read(n) for n in zf.namelist()}


def _resign_manifest(files: dict[str, bytes], seed: bytes) -> None:
    manifest = json.loads(files["manifest.json"])
    files["manifest.sig.json"] = jcs(chain.sign_manifest(seed, manifest))


def generate(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "README.md").write_text(README, encoding="utf-8", newline="\n")
    (out / "commitments.json").write_bytes(
        json.dumps(_commitments(), indent=2, ensure_ascii=False).encode() + b"\n"
    )

    def case(name: str, bundles: dict[str, bytes], expected: dict[str, Any]) -> None:
        folder = out / name
        folder.mkdir(parents=True, exist_ok=True)
        for file_name, data in bundles.items():
            (folder / file_name).write_bytes(data)
        (folder / "expected.json").write_bytes(json.dumps(expected, indent=2).encode() + b"\n")

    with tempfile.TemporaryDirectory() as tmp_text:
        tmp = Path(tmp_text)

        # intact: genesis, five events, a checkpoint in the middle, one at export
        clock = Clock()
        s = _store(tmp / "intact", SEED_1, clock)
        events = _events(clock)
        s.append([_genesis(SEED_1), *events[:3]])
        s.checkpoint()
        s.append(events[3:])
        intact, _ = s.export({"kind": "stream"}, "e0000000-0000-4000-8000-000000000001")
        case("intact", {"export.zip": intact}, {"verdict": "intact", "to_seq": 5})

        project, _ = s.export(
            {"kind": "project", "project_id": PROJECT_B}, "e0000000-0000-4000-8000-000000000002"
        )
        case(
            "project-scope",
            {"export.zip": project},
            {"verdict": "intact", "scope": {"kind": "project", "first_seq": 4, "last_seq": 4}},
        )

        # altered: the classification of project B changed in events.jsonl after export
        files = _unzip(intact)
        files["events.jsonl"] = files["events.jsonl"].replace(b'"internal"', b'"public"', 1)
        case("altered", {"export.zip": _zip(files)}, {"verdict": "altered"})

        # truncated: the last two events removed, the signed manifest kept
        files = _unzip(intact)
        lines = files["events.jsonl"].splitlines(keepends=True)
        files["events.jsonl"] = b"".join(lines[:-2])
        case(
            "truncated",
            {"export.zip": _zip(files)},
            {"verdict": "truncated", "error": "E_TRUNCATED"},
        )

        # unknown signer: the manifest re-signed with a key it does not name
        files = _unzip(intact)
        _resign_manifest(files, SEED_FOREIGN)
        case(
            "unknown-signer",
            {"export.zip": _zip(files)},
            {"verdict": "unknown_signer", "error": "E_UNKNOWN_SIGNER"},
        )

        # backup of the original device, then: restore elsewhere, and the original keeps writing
        backup = tmp / "backup" / "evidence.db"
        s.backup_to(backup)
        s.append(
            [
                Intent(
                    "after-backup",
                    "project_created",
                    "2026-11-12T09:30:00.000Z",
                    {
                        "project_id": "e5e5e5e5-0000-4000-8000-000000000005",
                        "classification": "public",
                    },
                )
            ]
        )
        original, _ = s.export({"kind": "stream"}, "e0000000-0000-4000-8000-000000000003")
        s.close()

        keys = MemoryKeys(SEED_1)  # the restored device holds the recovered key of epoch 1
        restored_store = EvidenceStore(tmp / "restored" / "evidence.db", keys, clock=Clock(40))
        real_new_seed = store_module.new_seed
        store_module.new_seed = lambda: SEED_2  # a fixed "new" key, for stable bytes
        try:
            restored_store.restore(backup, STREAM, min_tip_seq=5)
        finally:
            store_module.new_seed = real_new_seed
        restored_store.append(
            [
                Intent(
                    "after-restore",
                    "project_created",
                    "2026-11-12T09:45:00.000Z",
                    {
                        "project_id": "f6f6f6f6-0000-4000-8000-000000000006",
                        "classification": "public",
                    },
                )
            ]
        )
        restored, _ = restored_store.export(
            {"kind": "stream"}, "e0000000-0000-4000-8000-000000000004"
        )
        restored_store.close()
        case(
            "restore-two-signers",
            {"export.zip": restored},
            {
                "verdict": "intact",
                "epochs": [1, 2],
                "key_ids": [
                    chain.key_id(chain.public_key(SEED_1)),
                    chain.key_id(chain.public_key(SEED_2)),
                ],
            },
        )
        case(
            "branched",
            {"restored.zip": restored, "original.zip": original},
            {"verdict": "branched", "branch_after_seq": 5},
        )


def _snapshot(folder: Path) -> dict[str, bytes]:
    return {
        str(p.relative_to(folder)).replace("\\", "/"): p.read_bytes()
        for p in sorted(folder.rglob("*"))
        if p.is_file()
    }


def main(argv: list[str]) -> int:
    if "--check" in argv:
        with tempfile.TemporaryDirectory() as tmp_text:
            fresh = Path(tmp_text) / "v"
            generate(fresh)
            if _snapshot(fresh) != _snapshot(OUT):
                sys.stderr.write(
                    "evidence golden vectors are out of date: run "
                    "`uv run python tools/contracts/gen_evidence_vectors.py`\n"
                )
                return 1
        return 0
    for child in OUT.iterdir() if OUT.exists() else []:
        if child.is_dir():
            shutil.rmtree(child)
    generate(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
