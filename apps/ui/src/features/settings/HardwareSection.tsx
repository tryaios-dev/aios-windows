import { useState, type ReactNode } from "react";
import { Gauge } from "lucide-react";
import { api } from "@/bridge/api";
import { selectModelName, selectRecommendedTier, useStore } from "@/bridge/sim/store";
import { formatDateTime, relativeTime } from "@/lib/format";
import { MINIMUM_PROFILE } from "@/bridge/sim/catalogue";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/chips";
import { Callout, EmptyState, Progress } from "@/components/ui/feedback";
import { Ledger, PanelNote, SettingGroup, SettingPanel, SettingRow } from "@/components/app/SettingRow";
import { platform } from "@/lib/platform";

function timeToFirstWord(ms: number) {
  return ms < 1000 ? `${ms} ms` : `${(ms / 1000).toFixed(1)} s`;
}

/** Hardware: this machine and its benchmark (M-02, I-02). */
export function HardwareSection() {
  const hardware = useStore((s) => s.hardware);
  const tier = useStore(selectRecommendedTier);
  const installed = useStore((s) => s.installedModels);
  const generating = useStore((s) => !!s.generation);
  const benchModel = useStore(selectModelName(hardware.benchmark?.model_id));
  const [running, setRunning] = useState(false);
  const [failed, setFailed] = useState(false);

  const gpu = hardware.gpu;
  const benchmark = hardware.benchmark;
  const canRun = installed.length > 0 && !generating;

  const run = async () => {
    setRunning(true);
    setFailed(false);
    try {
      await api.system.benchmark();
    } catch {
      setFailed(true);
    } finally {
      setRunning(false);
    }
  };

  const tierValue =
    tier === "medium" ? (
      <TierValue tone="green" label="Medium">
        Runs the 8B class comfortably. 16 GB of memory, or a graphics card with 8 GB.
      </TierValue>
    ) : tier === "small" ? (
      <TierValue tone="neutral" label="Small">
        The 4B class on 8 GB machines, with or without a graphics card.
      </TierValue>
    ) : (
      <TierValue tone="brass" label="Below minimum">
        AIOS needs {MINIMUM_PROFILE.ram_gb} GB of memory and {MINIMUM_PROFILE.free_disk_gb} GB of free disk. Chat is
        unavailable until then.
      </TierValue>
    );

  return (
    <>
      <SettingGroup
        title="This machine"
        description="Read at start. AIOS recommends a model tier from it and never sends it anywhere."
      >
        <SettingPanel>
          <Ledger
            rows={[
              { k: "Processor", v: hardware.cpu, hint: <span className="tabular">{hardware.cores} cores</span> },
              { k: "Memory", v: `${hardware.ram_gb} GB`, mono: true },
              {
                k: "Graphics",
                v: gpu ? (
                  gpu.name
                ) : (
                  <span className="text-ink-soft">None AIOS can use. The engine runs on the CPU build.</span>
                ),
                hint: gpu ? (
                  <span className="flex flex-wrap items-center gap-2">
                    <span className="font-mono tabular">{gpu.vram_gb} GB VRAM</span>
                    {gpu.driver_ok ? (
                      <Badge tone="green">Driver OK</Badge>
                    ) : (
                      <Badge tone="brass">Driver not responding</Badge>
                    )}
                  </span>
                ) : undefined,
              },
              {
                k: "Free disk",
                v: `${hardware.free_disk_gb} GB`,
                mono: true,
                hint: "Models and the data folder share it",
              },
              { k: platform.os, v: hardware.os },
              { k: "Recommended tier", v: tierValue },
            ]}
          />
        </SettingPanel>
      </SettingGroup>

      <SettingGroup title="Benchmark">
        <SettingPanel>
          <SettingRow
            label="Run a benchmark"
            hint="A short fixed passage generated by the default model on this machine. Nothing leaves the device."
            control={
              <Button leading={<Gauge className="size-3.5" />} loading={running} disabled={!canRun} onClick={run}>
                {running ? "Measuring" : "Run benchmark"}
              </Button>
            }
          >
            {running && (
              <div aria-live="polite">
                <Progress indeterminate value={0} label="Benchmark running" />
                <p className="mt-2 text-xs leading-4.5 text-ink-50">
                  Loading the model and generating the passage. This takes a moment, longer on the CPU build.
                </p>
              </div>
            )}
            {failed && (
              <Callout tone="deny" compact title="The benchmark did not finish">
                The engine stopped before the passage was complete. Try again; if it keeps failing, turn on Safe mode
                (CPU) under Engine.
              </Callout>
            )}
          </SettingRow>
          {benchmark ? (
            <Ledger
              dense
              rows={[
                { k: "Tokens per second", v: benchmark.tokens_per_second.toFixed(1), mono: true },
                { k: "Time to first word", v: timeToFirstWord(benchmark.time_to_first_token_ms), mono: true },
                { k: "Engine build", v: benchmark.engine === "cpu" ? "CPU" : "GPU (Vulkan)", mono: true },
                { k: "Model", v: benchModel },
                {
                  k: "Measured",
                  v: (
                    <span className="tabular" title={formatDateTime(benchmark.run_at)}>
                      {relativeTime(benchmark.run_at)}
                    </span>
                  ),
                },
              ]}
            />
          ) : (
            !running && (
              <EmptyState
                compact
                icon={<Gauge />}
                title="No benchmark yet"
                description="Run one to see how fast answers are on this machine before a long conversation."
              />
            )
          )}
          {installed.length === 0 && (
            <PanelNote>Install a model first. The benchmark runs the default model.</PanelNote>
          )}
          {installed.length > 0 && generating && (
            <PanelNote>Wait for the current answer to finish before running a benchmark.</PanelNote>
          )}
        </SettingPanel>
      </SettingGroup>
    </>
  );
}

function TierValue({
  tone,
  label,
  children,
}: {
  tone: "green" | "neutral" | "brass";
  label: string;
  children: ReactNode;
}) {
  return (
    <span className="flex flex-col gap-1">
      <span>
        <Badge tone={tone}>{label}</Badge>
      </span>
      <span className="text-xs leading-4.5 text-ink-50">{children}</span>
    </span>
  );
}
